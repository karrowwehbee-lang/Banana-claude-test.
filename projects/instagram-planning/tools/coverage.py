"""Coverage of Karen's images on Instagram: every render she sent must appear in at least one post.

Writes COVERAGE.md from library.json, the queue (queue/*/post.json), the launch feed of 11 Nov and the plan below.
The daily and weekly runs pick new post renders first from the "not yet planned" list.
Also checks that Karen's original files never change: ORIGINALS.json keeps the fingerprint (md5) and size of each file
the first time it enters the library; any later difference fails the check.
Usage: python3 tools/coverage.py            (exit code 1 if a render is not planned or an original has changed)
"""
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAUNCH_FEED = {"chambre-principale-02", "etage1-sejour-02", "rdc-salon-11", "rdc-salon-05", "r13", "r20", "r21"}  # 11 Nov
PLANNED = {   # render: when / which post (specs written when the date approaches, so rotation rules hold)
}
AWAITING_KAREN = {   # sent by Karen but not publishable until she decides (16 Nov 2026: all confirmed — none left)
}


def originals_unchanged(lib):
    """Karen's files stay exactly as she sent them: same bytes, same full resolution, never cropped or retouched."""
    from PIL import Image
    rec_file = ROOT / "ORIGINALS.json"
    rec = json.loads(rec_file.read_text()) if rec_file.exists() else {}
    repo, changed = ROOT.parent.parent, []
    for rid, d in lib.items():
        f = repo / d["path"]
        now = {"path": d["path"], "md5": hashlib.md5(f.read_bytes()).hexdigest(), "pixels": list(Image.open(f).size)}
        if rid not in rec:
            rec[rid] = now
        elif rec[rid] != now:
            changed.append(rid)
    rec_file.write_text(json.dumps(rec, indent=1, ensure_ascii=False))
    return changed


def main():
    lib = json.loads((ROOT / "library.json").read_text())
    changed = originals_unchanged(lib)
    used = {}
    for f in sorted((ROOT / "queue").glob("*/post.json")):
        m = json.loads(f.read_text())
        for r in m["renders"]:
            used.setdefault(r, []).append(f"{m['id']} ({m['status']})")
    rows, missing = [], []
    for rid, d in lib.items():
        if d.get("dup_of"):
            continue
        st = []
        if rid in LAUNCH_FEED:
            st.append("launch feed 11 Nov (published)")
        st += used.get(rid, [])
        if not st and rid in PLANNED:
            st.append("planned: " + PLANNED[rid])
        if not st:
            missing.append(rid)
            st.append("**NOT YET PLANNED**")
        flags = ", ".join(x for x, on in (("screen on", d["tv_on"]), ("brand logos", d["brands"])) if on)
        rows.append(f"| {rid} | {d['project']} | {d['space']} | {flags} | {'; '.join(st)} |")
    out = ["# KAÏRA — Instagram coverage of Karen's images", "",
           "Generated by `tools/coverage.py`. Every render Karen sent is listed once (exact duplicates are merged).", "",
           f"**{len(rows)} renders · {len(rows) - len(missing)} published, queued or planned · {len(missing)} not yet planned.**", "",
           f"**Originals:** {len(lib) - len(changed)} / {len(lib)} identical to the files Karen sent (same bytes, full "
           "resolution, never cropped or retouched; fingerprints in `ORIGINALS.json`)"
           + (f" — **CHANGED: {', '.join(changed)}**" if changed else "") + ".", "",
           "| Render | Project | Space | Note | Instagram |", "|---|---|---|---|---|", *rows, "",
           "## Waiting for Karen's decision", "", "| File | Question |", "|---|---|",
           *[f"| `{k}` | {v} |" for k, v in AWAITING_KAREN.items()], "",
           "## Not Karen's images (never published unless she asks)", "",
           "Images generated during design studies (`projects/villa-rdc/renders/`, `projects/chambre-blender/renders/`) "
           "are not KAÏRA renders sent by Karen; they stay out unless she approves them (confirmed 16 Nov 2026).", "",
           "## Sent by Karen but not design content", "",
           "Three screenshots of the Cloudflare dashboard (website set-up, 13 Nov): kept off Instagram, Karen's decision of 16 Nov 2026.", ""]
    (ROOT / "COVERAGE.md").write_text("\n".join(out))
    print(f"{len(rows)} renders, {len(missing)} not yet planned", missing or "",
          f"| originals unchanged: {len(lib) - len(changed)}/{len(lib)}", changed or "")
    return 1 if missing or changed else 0


if __name__ == "__main__":
    sys.exit(main())
