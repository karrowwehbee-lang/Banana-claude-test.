"""Publishing calendar: one feed post a day at 17:37 GMT, in queue order (lowest ready id first).
Writes CALENDAR.md from history.json (published) and queue/*/post.json (ready / hold / changes).
Usage: python3 tools/calendar.py
"""
import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
lib = json.loads((ROOT / "library.json").read_text())
posts = [json.loads(f.read_text()) for f in sorted((ROOT / "queue").glob("*/post.json"))]
today = datetime.datetime.now(datetime.timezone.utc)
pub = [p for p in posts if p["status"] == "published"]
day = today.date() if not any((p.get("published_at") or "").startswith(today.date().isoformat()) for p in pub) \
    else today.date() + datetime.timedelta(days=1)
if today.hour > 17 or (today.hour == 17 and today.minute > 45):
    day = max(day, today.date() + datetime.timedelta(days=1))


def project(p):
    names = sorted({lib[r]["project"] for r in p["renders"] if r in lib})
    return " + ".join(names)


rows = []
for p in pub:
    rows.append(f"| {p['published_at'][:10]} | {p['id']} | {p['caption'].splitlines()[0]} | {p['kind']} | {project(p)} | "
                f"published — [link]({p['permalink']}) |")
for p in [p for p in posts if p["status"] == "ready"]:
    rows.append(f"| {day.isoformat()} ({day.strftime('%a')}) | {p['id']} | {p['caption'].splitlines()[0]} | {p['kind']} | "
                f"{project(p)} | ready |")
    day += datetime.timedelta(days=1)
held = [p for p in posts if p["status"] not in ("ready", "published")]
out = ["# KAÏRA — Instagram calendar", "",
       f"Generated by `tools/calendar.py` on {today:%Y-%m-%d %H:%M} UTC. One feed post a day at 17:37 GMT (18:37 Paris), "
       "in queue order. Dates of ready posts move by one day if a day is skipped.", "",
       "| Date | Post | Title | Format | Project | Status |", "|---|---|---|---|---|---|", *rows, ""]
if held:
    out += ["## Not scheduled (hold / changes / unconfirmed)", "", *[f"- {p['id']} {p['caption'].splitlines()[0]} — {p['status']}" for p in held], ""]
(ROOT / "CALENDAR.md").write_text("\n".join(out))
print("\n".join(rows[-26:]))
